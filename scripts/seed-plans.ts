async function main() {
  console.log('Seeding vehicle classes...')
  const classMap = new Map<string, string>()

  for (let i = 0; i < VEHICLE_CLASSES.length; i++) {
    const vc = VEHICLE_CLASSES[i]
    const created = await db.vehicleClass.upsert({
      where: { code: vc.code },
      create: { code: vc.code, name: vc.name, sortOrder: i },
      update: { name: vc.name, sortOrder: i },
    })
    classMap.set(vc.name, created.id)
  }
  console.log(`  ✓ ${VEHICLE_CLASSES.length} vehicle classes seeded`)

  console.log('Seeding plans...')
  let count = 0
  for (const [extId, className, name, eur, usd, bs] of PLANS) {
    const classId = classMap.get(className)
    if (!classId) {
      console.warn(`  ⚠ Class "${className}" not found for plan ${extId}, skipping`)
      continue
    }
    await db.plan.upsert({
      where: { externalId: extId },
      create: {
        externalId: extId,
        name,
        vehicleClassId: classId,
        priceEur: eur,
        priceUsd: usd,
        priceBs: bs,
      },
      update: {
        name,
        vehicleClassId: classId,
        priceEur: eur,
        priceUsd: usd,
        priceBs: bs,
      },
    })
    count++
  }
  console.log(`  ✓ ${count} plans seeded`)
  console.log('Done!')
}

main()
  .catch((e) => {
    console.error(e)
    process.exit(1)
  })
  .finally(async () => {
    await db.$disconnect()
  })
